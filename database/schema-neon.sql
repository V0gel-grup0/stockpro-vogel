create table if not exists public.profiles (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  role public.app_role not null default 'representante',
  status public.account_status not null default 'pending',
  name text not null default '',
  document text not null default '',
  phone text not null default '',
  cep text not null default '',
  city text not null default '',
  street text not null default '',
  number text not null default '',
  no_number boolean not null default false,
  neighborhood text not null default '',
  access_code text,
  seller_code text,
  manager_code text,
  responsible_seller_id uuid references public.profiles(id),
  responsible_manager_id uuid references public.profiles(id),
  created_by uuid references public.profiles(id),
  permissions jsonb not null default '{}'::jsonb,
  approval_notes text,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

