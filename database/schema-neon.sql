create table if not exists public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  document text not null default '',
  phone text not null default '',
  email text not null default '',
  cep text not null default '',
  city text not null default '',
  street text not null default '',
  number text not null default '',
  no_number boolean not null default false,
  neighborhood text not null default '',
  products text[] default '{}',
  created_at timestamp with time zone default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  sku text not null default '',
  category text not null default '',
  subcategory text not null default '',
  cost_price numeric not null default 0,
  sale_price numeric not null default 0,
  quantity integer not null default 0,
  min_stock integer not null default 0,
  supplier_id uuid references public.suppliers(id),
  description text not null default '',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

alter table public.products add column if not exists subcategory text not null default '';
create unique index if not exists products_sku_unique on public.products(sku) where sku <> '';

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  document text not null default '',
  phone text not null default '',
  cep text not null default '',
  city text not null default '',
  street text not null default '',
  number text not null default '',
  no_number boolean not null default false,
  neighborhood text not null default '',
  created_by uuid references public.profiles(id),
  created_at timestamp with time zone default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity,
  created_by uuid references public.profiles(id),
  client_id uuid references public.clients(id),
  status text not null default 'pendente',
  item_type text not null default '',
  item_id uuid,
  equipment_name text not null default '',
  quantity integer not null default 1,
  total_value numeric not null default 0,
  shipping_value numeric not null default 0,
  tracking_code text not null default '',
  tracking_location text not null default '',
  conta_azul_status text not null default '',
  notes text not null default '',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

alter table public.orders add column if not exists equipment_name text not null default '';
